-- 用 IF NOT EXISTS：幂等，若该值已被手工加入也不报错（PG12+ 支持，可在事务块内）。
--
-- 无新表、无新列、无存量回填；PG 枚举值不可删，回滚 = 不回滚（留存无害）。
